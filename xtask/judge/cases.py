def main(argv):
    out = argv[1]
    rungs = argv[2:] or ["R0", "R1", "R3", "R4", "G22", "G24", "FB"]
    os.makedirs(out, exist_ok=True)
    r3 = None
    for rung in rungs:
        rng = random.Random(SEEDS.get(rung, 0))
        if rung == "R0":
            cs = gen_R0(rng)
        elif rung == "R1":
            cs = gen_R1(rng)
        elif rung == "R3":
            cs = gen_class_cases(rng, "R3", 100, R3_CLASSES, "R3")
            r3 = cs
        elif rung == "R4":
            cs = gen_R4(rng)
        elif rung == "G22":
            if r3 is None:
                with gzip.open(os.path.join(out, "R3.cases.jsonl.gz"), "rt") as f:
                    r3 = [json.loads(l) for l in f]
            cs = gen_G22(rng, r3)
        elif rung == "G24":
            cs = gen_G24(rng)
        elif rung == "FB":
            cs = gen_FB(rng)
        elif rung == "R5":
            pinned = ["bound", "unbound", "plunging", "radial", "null"]
            cs = gen_class_cases(rng, "R5", int(os.environ.get("R5_PINNED", "4000")), pinned, "R5")
            special = [c for c in R3_CLASSES if c not in pinned]
            cs += gen_class_cases(rng, "R5", int(os.environ.get("R5_SPECIAL", "300")), special, "R5s")
        else:
            raise SystemExit(f"unknown rung {rung}")
        write(os.path.join(out, f"{rung}.cases.jsonl.gz"), cs)
        print(rung, len(cs), file=sys.stderr)


if __name__ == "__main__":
    sys.exit(main(sys.argv))
