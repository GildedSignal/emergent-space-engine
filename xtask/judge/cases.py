# G2.2: bound anchors with (p - p_sep)/p >= 1e-4 and scattering null anchors, 16 T each


def gen_G22(rng, r3_cases):
    cases = []
    for c in r3_cases:
        cl = c["class"]
        if cl[0] not in ("bound", "null", "long-T", "near-circular", "near-isco", "near-separatrix"):
            continue
        ci = to_case_ints(c)
        g = geo(ci["M"], ci["Q"], ci["x"], ci["k"], ci["motion"] == "null")
        if g is None:
            continue
        if ci["motion"] == "null":
            if not (g.escape and g.chart == "three-root" and getattr(g, "region", None) == "A"):
                continue
            ts = time_scale(g)
        else:
            if not g.period:
                continue
            u1, u2 = g.roots[0], g.roots[1]
            p = 2 / (g.Mb * (u1 + u2))
            e = (u2 - u1) / (u1 + u2)
            if not (p - 6 - 2 * e) / p >= arb(10) ** -4:
                continue
            ts = 10 * float((g.PT / g.Qb).mid())
        t0 = ci["t0"]
        Ts = sorted({t0 + max(1, int(2.0 ** rng.uniform(0, math.log2(max(ts, 2))))) for _ in range(16)})
        while len(Ts) < 16:
            Ts = sorted(set(Ts) | {Ts[-1] + len(Ts)})
        cases.append(mk(f"G22-{len(cases):04d}", "G22", ["G2.2", cl[0]], ci["M"], ci["Q"], t0,
                        ci["x"], ci["k"], ci["motion"] == "null", Ts, source=c["id"], diag=True))
    return cases


