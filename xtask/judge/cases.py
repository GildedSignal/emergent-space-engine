# Anchors


def geo(M, Q, x, k, null, prec=256):
    """Validated geodesic at `prec`, or None when invalid or undecidable there."""
    try:
        A = gj.Anchor(M, Q, 0, x, k, null)
        return gj.Geo(A, prec)
    except (gj.Invalid, gj.Undecided):
        return None


def rand_int_near(rng, v):
    """An integer near the float v, with random low bits below the float's resolution."""
    iv = int(round(v))
    m = max(0, int(math.log2(abs(v) + 1)) - 50)
    if m:
        iv += rng.randrange(-(1 << m), 1 << m)
    return iv


def clip(v):
    return max(-LIM, min(LIM, v))


def pinned_anchor(rng, null, lm_range=(0.0, 80.0), lq_range=(4.0, 40.0), rmax_log=96.0):
    """The pinned sampler: log2 M ~ U(lm_range), log2 Q ~ U(lq_range), r/M log-uniform over
    (2, 2^rmax_log / M], direction uniform, speed relative to the flow ~ U[0, 0.95c] in a
    uniform direction (timelike), or a uniform null direction with |k| = 2^U(0, 40)."""
    while True:
        lm = rng.uniform(*lm_range)
        M = max(1, int(round(2 ** lm)))
        Q = max(1, int(round(2 ** rng.uniform(*lq_range))))
        top = rmax_log - math.log2(M)
        if top <= 1.0:
            continue
        lr = rng.uniform(1.0, top)
        r = M * 2.0 ** lr
        th = rng.uniform(0, 2 * math.pi)
        x = (clip(rand_int_near(rng, r * math.cos(th))), clip(rand_int_near(rng, r * math.sin(th))))
        n = x[0] ** 2 + x[1] ** 2
        if n <= 4 * M * M:
            continue
        rr = math.sqrt(n)
        psi = rng.uniform(0, 2 * math.pi)
        if null:
            km = 2.0 ** rng.uniform(0, 40)
            k = (int(round(km * math.cos(psi))), int(round(km * math.sin(psi))))
            if k == (0, 0):
                continue
        else:
            sp = rng.uniform(0, 0.95)
            fb = -math.sqrt(2 * M / rr)
            k = (int(round(Q * (fb * x[0] / rr + sp * math.cos(psi)))),
                 int(round(Q * (fb * x[1] / rr + sp * math.sin(psi)))))
        g = geo(M, Q, x, k, null)
        if g is None:
            continue
        return M, Q, x, k, g


def radial_anchor(rng, null):
    """Radial anchors: x0 = g (p, q) with a small primitive direction, k0 parallel to it."""
    while True:
        lm = rng.uniform(0, 80)
        M = max(1, int(round(2 ** lm)))
        Q = max(1, int(round(2 ** rng.uniform(4, 40))))
        top = 96 - math.log2(M)
        if top <= 1.0:
            continue
        r = M * 2.0 ** rng.uniform(1.0, top)
        if rng.random() < 0.3:
            p, q = rng.choice([(1, 0), (0, 1), (-1, 0), (0, -1)])
        else:
            e = rng.randint(0, 12)
            while True:
                p, q = rng.randint(-2 ** e, 2 ** e), rng.randint(-2 ** e, 2 ** e)
                if (p, q) != (0, 0) and math.gcd(p, q) == 1:
                    break
        h = math.hypot(p, q)
        g = max(1, rand_int_near(rng, r / h))
        x = (g * p, g * q)
        if max(abs(x[0]), abs(x[1])) > LIM:
            continue
        if null:
            s = rng.choice([1, -1])
            k = (s * p, s * q)
        else:
            rr = math.sqrt(x[0] ** 2 + x[1] ** 2)
            ur = rng.uniform(-0.95, 0.95)
            vr = -math.sqrt(2 * M / rr) + ur
            mult = int(round(Q * vr / h))
            if rng.random() < 0.1:
                mult = 0                    # at rest in the coordinates
            k = (mult * p, mult * q)
        gg = geo(M, Q, x, k, null)
        if gg is None:
            continue
        return M, Q, x, k, gg


def time_scale(g):
    """Upper end (chronons) of the pinned log-uniform T - T0 draw for this geodesic."""
    kind = g.info.get("kind")
    Q = g.A.Q
    if g.period:
        tmax = 1e4 * float((g.PT / g.Qb).mid())
    elif g.chart == "circular":
        tmax = 1e4 * float((2 * arb.pi() / (g.omega * g.Qb)).mid())
    elif g.horizon:
        tmax = 4 * float((g.dTh / g.Qb).mid())
    else:
        # escaping: twice the time to reach r = 2^97 at the asymptotic speed
        E = float(g.E.mid())
        if g.A.null:
            v = 1.0
        else:
            v = math.sqrt(max(E * E - 1, 1e-300)) / E
        tmax = 2 * (2.0 ** 97 + math.sqrt(g.A.n)) / (max(v, 1e-30) * Q)
    return max(2.0, min(tmax, float(TWO80)))


def draw_dt(rng, tmax):
    return max(1, int(2.0 ** rng.uniform(0, math.log2(tmax))))


