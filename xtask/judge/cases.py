def near_circular_velocity(M, x, Q, delta, rng, sign):
    r = math.hypot(*x)
    v = math.sqrt(M / r) * (1 + delta)
    tx, ty = -x[1] / r * sign, x[0] / r * sign
    # small radial perturbation too
    vr = math.sqrt(M / r) * delta * rng.uniform(-1, 1)
    return (int(round(Q * (v * tx + vr * x[0] / r))), int(round(Q * (v * ty + vr * x[1] / r))))


def class_anchor(rng, cls):
    """(M, Q, x, k, null, g, dt_or_None, notes) for one R3/R5 class."""
    if cls in ("bound", "unbound", "plunging"):
        while True:
            M, Q, x, k, g = pinned_anchor(rng, False)
            if g.info.get("kind") == cls:
                return M, Q, x, k, False, g, None, {}
    if cls == "radial":
        null = rng.random() < 0.2
        M, Q, x, k, g = radial_anchor(rng, null)
        return M, Q, x, k, null, g, None, {"kind": g.info["kind"]}
    if cls == "null":
        M, Q, x, k, g = pinned_anchor(rng, True)
        return M, Q, x, k, True, g, None, {"kind": g.info["kind"]}
    if cls in ("near-circular", "near-isco"):
        while True:
            M = max(1, int(round(2 ** rng.uniform(0, 70))))
            Q = 2 ** 40
            if cls == "near-isco":
                rM = rng.uniform(5.9, 6.2)
            else:
                rM = 2.0 ** rng.uniform(math.log2(7), min(60, 96 - math.log2(M) - 0.5))
            th = rng.uniform(0, 2 * math.pi)
            r = rM * M
            x = (rand_int_near(rng, r * math.cos(th)), rand_int_near(rng, r * math.sin(th)))
            delta = 10.0 ** rng.uniform(-9, -3) * rng.choice([1, -1])
            k = near_circular_velocity(M, x, Q, delta, rng, rng.choice([1, -1]))
            g = geo(M, Q, x, k, False)
            if g is None:
                continue
            return M, Q, x, k, False, g, None, {"delta": delta, "r_over_M": rM}
    if cls == "near-separatrix":
        while True:
            M = max(1, int(round(2 ** rng.uniform(0, 70))))
            Q = 2 ** 40
            if rng.random() < 0.5:
                # tangential periapsis just outside an unstable circular orbit, 4M < r < 6M
                rM = rng.uniform(4.05, 5.95)
                r = int(round(rM * M))
                eps_ = 10.0 ** rng.uniform(-10, -2)
                v = math.sqrt(M / r * (1 + eps_))
                x, k = (r, 0), (0, int(round(Q * v)))
            else:
                # tangential apoapsis of an orbit whose periapsis is near the separatrix
                e = rng.uniform(0.05, 0.9)
                p = 6 + 2 * e + (6 + 2 * e) * 10.0 ** rng.uniform(-9, -3)
                ra = p / (1 - e)
                L2 = p * p / (p - 3 - e * e)                  # (L/M)^2
                r = int(round(ra * M))
                rr = r / M
                v = math.sqrt(L2 * (1 - 2 / rr) / (rr * rr + L2))
                x, k = (r, 0), (0, int(round(Q * v)))
            s = rng.randint(0, 3)
            for _ in range(s):
                x, k = (-x[1], x[0]), (-k[1], k[0])
            if rng.random() < 0.5:
                k = (-k[0], -k[1])
            g = geo(M, Q, x, k, False)
            if g is None:
                continue
            return M, Q, x, k, False, g, None, {}
    if cls == "near-horizon":
        while True:
            M = max(1, int(round(2 ** rng.uniform(40, 80))))
            Q = max(1, int(round(2 ** rng.uniform(4, 40))))
            rM = 2 * (1 + 10.0 ** rng.uniform(-9, -1))
            th = rng.uniform(0, 2 * math.pi)
            r = rM * M
            x = (rand_int_near(rng, r * math.cos(th)), rand_int_near(rng, r * math.sin(th)))
            null = rng.random() < 0.25
            rr = math.hypot(*x)
            psi = rng.uniform(0, 2 * math.pi)
            if null:
                km = 2.0 ** rng.uniform(0, 40)
                k = (int(round(km * math.cos(psi))), int(round(km * math.sin(psi))))
                if k == (0, 0):
                    continue
            else:
                sp = rng.uniform(0, 0.95)
                fb = -math.sqrt(2 * M / rr)
                k = (int(round(Q * (fb * x[0] / rr + sp * math.cos(psi)))),
                     int(round(Q * (fb * x[1] / rr + sp * math.sin(psi)))))
            g = geo(M, Q, x, k, null)
            if g is None:
                continue
            return M, Q, x, k, null, g, None, {"r_over_M": rM}
    if cls in ("T=T0", "T<T0"):
        null = rng.random() < 0.25
        M, Q, x, k, g = pinned_anchor(rng, null)
        return M, Q, x, k, null, g, None, {}
    if cls == "long-T":
        while True:
            M, Q, x, k, g = pinned_anchor(rng, False)
            if g.period:
                P = float((g.PT / g.Qb).mid())
                dt = int(P * 10.0 ** rng.uniform(3, 4))
                if 1 <= dt <= TWO80:
                    return M, Q, x, k, False, g, dt, {"periods": dt / P}
    if cls == "range-exit":
        while True:
            M = max(1, int(round(2 ** rng.uniform(0, 80))))
            Q = max(1, int(round(2 ** rng.uniform(4, 40))))
            c = rng.randint(0, 1)
            sgn = rng.choice([1, -1])
            edge = sgn * (LIM - int(2 ** rng.uniform(0, 60)))
            other = rng.randint(-LIM, LIM)
            x = (edge, other) if c == 0 else (other, edge)
            null = rng.random() < 0.25
            rr = math.hypot(*x)
            psi = rng.uniform(-math.pi / 2, math.pi / 2)        # outward in component c
            dirc = (math.cos(psi), math.sin(psi)) if c == 0 else (math.sin(psi), math.cos(psi))
            dirc = (dirc[0] * (sgn if c == 0 else 1), dirc[1] * (sgn if c == 1 else 1))
            if null:
                km = 2.0 ** rng.uniform(0, 40)
                k = (int(round(km * dirc[0])), int(round(km * dirc[1])))
                if k == (0, 0):
                    continue
            else:
                sp = rng.uniform(0.001, 0.95)
                fb = -math.sqrt(2 * M / rr)
                k = (int(round(Q * (fb * x[0] / rr + sp * dirc[0]))),
                     int(round(Q * (fb * x[1] / rr + sp * dirc[1]))))
            g = geo(M, Q, x, k, null)
            if g is None:
                continue
            # T well past the straight-line exit estimate
            vc = abs(k[c]) if not null else Q * abs(dirc[c])
            if vc == 0:
                continue
            est = (LIM - abs(x[c])) / vc + 1
            dt = int(min(float(TWO80), est * 2.0 ** rng.uniform(-1, 20))) + 1
            return M, Q, x, k, null, g, dt, {}
    raise ValueError(cls)


def gen_class_cases(rng, rung, per_class, classes, prefix):
    cases = []
    for cls in classes:
        for i in range(per_class):
            M, Q, x, k, null, g, dt, notes = class_anchor(rng, cls)
            t0 = rng.randint(-2 ** 40, 2 ** 40)
            if cls == "T=T0":
                T = t0
            elif cls == "T<T0":
                T = t0 - max(1, int(2.0 ** rng.uniform(0, 80)))
            else:
                if dt is None:
                    dt = draw_dt(rng, time_scale(g))
                T = t0 + dt
            cl = [cls, g.info.get("kind"), g.chart]
            cases.append(mk(f"{prefix}-{len(cases):05d}", rung, cl, M, Q, t0, x, k, null, [T],
                            **({"notes": notes} if notes else {})))
    return cases


