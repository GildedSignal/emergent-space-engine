# G2.4: horizon


def conic_points(rng, base, F, B, n, ratio, window):
    """Integer points on the conic F(v) = 0 through `base` (projective lines through it)."""
    out = []
    tries = 0
    while len(out) < n and tries < 200000:
        tries += 1
        D = [rng.randint(-2 ** 12, 2 ** 12) for _ in range(3)]
        fd = F(D)
        if fd == 0:
            continue
        b = B(base, D)
        P = [fd * base[i] - 2 * b * D[i] for i in range(3)]
        g = math.gcd(math.gcd(abs(P[0]), abs(P[1])), abs(P[2]))
        if g == 0:
            continue
        P = [v // g for v in P]
        if P[0] < 0:
            P = [-v for v in P]
        Q, a, kk = P
        if Q <= 0 or a <= 0 or Q > 2 ** 40:
            continue
        rt = ratio(Q, a, kk)
        if window(rt):
            out.append((Q, a, kk, rt))
    return out


def gen_G24(rng):
    cases = []
    # (a) radial infall from rest (k0 = 0) at r0 in {10M, 100M}
    dirs = [((1, 0), 1), ((0, -1), 1), ((3, 4), 5), ((-4, 3), 5), ((-8, -6), 10)]
    for rM in (10, 100):
        for (M, Q) in [(1, 1), (1, 25), (7, 3), (12345, 2 ** 20), (2 ** 40, 2 ** 20), (2 ** 60, 2 ** 40),
                       (2 ** 70 + 11, 2 ** 40), (3 ** 40, 2 ** 33)]:
            for (d, h) in dirs:
                r0 = rM * M
                if r0 % h:
                    continue
                g0 = r0 // h
                x = (g0 * d[0], g0 * d[1])
                if max(abs(x[0]), abs(x[1])) > LIM:
                    continue
                g = geo(M, Q, x, (0, 0), False, 512)
                th_cf = gj.closed_form_infall_from_rest(M, Q, r0)
                dq = g.dTh / g.Qb
                if not (abs(dq - th_cf) < abs(th_cf) * arb(2) ** -200):
                    raise SystemExit(f"closed form mismatch {M} {Q} {r0}")
                t0 = rng.randint(-2 ** 40, 2 ** 40)
                ch = gj.ceil_int(t0 + th_cf, "g24")
                if ch - t0 > TWO80:
                    continue
                Ts = [t0 + 1, ch - 1, ch, ch + 1, ch + 2 ** 40]
                Ts = sorted({T for T in Ts if T > t0})
                cases.append(mk(f"G24-{len(cases):04d}", "G24", ["G2.4", "infall-from-rest", f"r0={rM}M"],
                                M, Q, t0, x, (0, 0), False, Ts,
                                T_h_closed_form=(t0 + th_cf).mid().str(60, radius=False)))
    # (b) E = 1 inward anchors on the branch from infinity: r0 = 2 M j^2 on an axis,
    # conic Q^2 (j^2 - 1) + 2 a Q j - a^2 j^2 (j^2 + 1) = k^2 j^4 with k0 = (-a, k).
    for j, base in ((2, (14, 3, 6)), (3, (111, 28, 24))):
        F = lambda v, j=j: v[0] * v[0] * (j * j - 1) + 2 * v[1] * v[0] * j - v[1] * v[1] * j * j * (j * j + 1) - v[2] * v[2] * j ** 4
        B = lambda u, v, j=j: (u[0] * v[0] * (j * j - 1) + j * (u[1] * v[0] + u[0] * v[1])
                               - u[1] * v[1] * j * j * (j * j + 1) - u[2] * v[2] * j ** 4)
        assert F(base) == 0
        ratio = lambda Q, a, kk, j=j: 2 * j ** 4 * abs(kk) / (Q * j * j + a * j - Q) / 4   # |L|/(4M)
        for side, window in (("absorbed", lambda t: 1 - 1e-2 < t <= 1 - 1e-6),
                             ("escapes", lambda t: 1 + 1e-6 <= t < 1 + 1e-2)):
            pts = conic_points(rng, list(base), F, B, 60, ratio, window)
            # keep a spread, including the closest to the band edge
            pts.sort(key=lambda p: abs(p[3] - 1))
            pick = pts[:10] + rng.sample(pts[10:], min(20, len(pts) - 10))
            for (Q, a, kk, rt) in pick:
                M = max(1, int(round(2 ** rng.uniform(0, 70))))
                r0 = 2 * M * j * j
                s = rng.randint(0, 3)
                x, k = (r0, 0), (-a, kk if rng.random() < 0.5 else -kk)
                for _ in range(s):
                    x, k = (-x[1], x[0]), (-k[1], k[0])
                A = gj.Anchor(M, Q, 0, x, k, False)
                if not A.E_one:
                    raise SystemExit("E = 1 construction failed")
                g = geo(M, Q, x, k, False, 512)
                if g is None:
                    continue
                exact_ratio = g.Lab / (4 * g.Mb)
                kind = g.info["kind"]
                expect = "plunging" if side == "absorbed" else "unbound"
                if kind != expect:
                    raise SystemExit(f"G2.4 E=1 class mismatch {kind} {side}")
                t0 = rng.randint(-2 ** 40, 2 ** 40)
                if g.horizon:
                    ch = gj.ceil_int(t0 + g.dTh / g.Qb, "g24b")
                    Ts = [ch - 1, ch, ch + 2 ** 30]
                else:
                    ts = time_scale(g)
                    Ts = [t0 + max(1, int(ts / 2 ** 20)), t0 + max(2, int(ts / 1000)), t0 + int(ts)]
                Ts = sorted({T for T in Ts if T > t0})
                cases.append(mk(f"G24-{len(cases):04d}", "G24", ["G2.4", "E=1", side, f"j={j}"],
                                M, Q, t0, x, k, False, Ts,
                                L_over_4M=exact_ratio.mid().str(30, radius=False)))
    return cases


