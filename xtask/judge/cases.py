# Fallback cases at |X| <= 2^12


def lll_inhomogeneous(alpha, beta, J):
    """Integer j in (0, ~J] with jalpha + beta close to an integer (Kannan embedding)."""
    C = J * J
    Bm = fmpz_mat([[1, 0, int((alpha * C).mid().floor().unique_fmpz())],
                   [0, 0, C],
                   [0, J, int((beta * C).mid().floor().unique_fmpz())]])
    R = Bm.lll()
    best = None
    for i in range(3):
        row = [int(R[i, c]) for c in range(3)]
        if abs(row[1]) == J:
            s = 1 if row[1] == J else -1
            jj = s * row[0]
            if jj > 0 and (best is None or abs(row[2]) < abs(best[1])):
                best = (jj, row[2])
    return best[0] if best else None


def gen_FB(rng, n_circ=150, n_other=150):
    """Small-magnitude near-integer cases for the forced-fallback test."""
    cases = []
    ctx.prec = 1024
    # (a) circular: x0 = (r, 0), r = M w^2, Q = w, k0 = (0, +-1): X = r (cos, sin)(dt / r).
    # Pick an integer n in (-r, r); find dt with dt/r = 2 pi j + theta*, cos theta* = n/r,
    # to within 2^-60 by an inhomogeneous Diophantine approximation (LLL).
    while len([c for c in cases if "circular" in c["class"]]) < n_circ:
        M = max(1, int(round(2 ** rng.uniform(0, 8))))
        w = rng.randint(2, max(2, int(math.sqrt(2 ** 12 / M))))
        r = M * w * w
        if r > 2 ** 12 or r <= 3 * M:
            continue
        n = rng.randint(-r + 1, r - 1)
        if n == 0:
            continue
        sgn_ = rng.choice([1, -1])
        th = (arb(n) / r).acos() * (1 if rng.random() < 0.5 else -1)
        alpha = 2 * arb.pi() * r
        beta = th * r
        J = 2 ** rng.randint(40, 62)
        jj = lll_inhomogeneous(alpha, beta, J)
        if jj is None:
            continue
        cand = int((alpha * jj + beta + arb(1) / 2).mid().floor().unique_fmpz())   # nearest
        if cand <= 0 or cand > TWO80:
            continue
        x, k = (r, 0), (0, sgn_)
        t0 = rng.randint(-2 ** 40, 2 ** 40)
        cases.append(mk(f"FB-{len(cases):04d}", "FB", ["fallback", "circular"], M, w, t0, x, k, False,
                        [t0 + cand], target_integer=S(n), coord=0))
    # (b) other charts: small anchors, keep the queries whose coordinate is nearest an integer
    pool = []
    tries = 0
    while tries < 6000:
        tries += 1
        null = rng.random() < 0.25
        M = max(1, int(round(2 ** rng.uniform(0, 7))))
        Q = max(1, int(round(2 ** rng.uniform(2, 40))))
        r = M * 2 ** rng.uniform(1.2, math.log2(2 ** 11 / M))
        th = rng.uniform(0, 2 * math.pi)
        x = (int(round(r * math.cos(th))), int(round(r * math.sin(th))))
        psi = rng.uniform(0, 2 * math.pi)
        if null:
            k = (int(round(2 ** 20 * math.cos(psi))), int(round(2 ** 20 * math.sin(psi))))
        else:
            rr = math.hypot(*x)
            if rr <= 2 * M:
                continue
            sp = rng.uniform(0, 0.95)
            fb = -math.sqrt(2 * M / rr)
            k = (int(round(Q * (fb * x[0] / rr + sp * math.cos(psi)))),
                 int(round(Q * (fb * x[1] / rr + sp * math.sin(psi)))))
        g = geo(M, Q, x, k, null)
        if g is None:
            continue
        for _ in range(4):
            dt = draw_dt(rng, min(time_scale(g), 2.0 ** 40))
            try:
                res = g.query(dt)
            except gj.Undecided:
                continue
            if res["at"] != "Free" or max(abs(v) for v in res["x"]) >= 2 ** 12:
                continue
            ds = [d for d in res["dist"] if d is not None]
            if not ds:
                continue
            pool.append((min(ds), M, Q, x, k, null, dt, "null" if null else g.chart))
    pool.sort()
    for (d, M, Q, x, k, null, dt, ch) in pool[:n_other]:
        t0 = rng.randint(-2 ** 40, 2 ** 40)
        cases.append(mk(f"FB-{len(cases):04d}", "FB", ["fallback", ch], M, Q, t0, x, k, null, [t0 + dt],
                        search_log2_dist=d))
    return cases


