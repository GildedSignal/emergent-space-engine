# R0: controls a straight line passes


def gen_R0(rng):
    cases = []
    # T = T0 (any anchor)
    for i in range(100):
        null = i % 4 == 3
        M, Q, x, k, g = pinned_anchor(rng, null)
        t0 = rng.randint(-2 ** 60, 2 ** 60)
        cases.append(mk(f"R0-{len(cases):04d}", "R0", ["T=T0"], M, Q, t0, x, k, null, [t0]))
    # Far-field hops, on an axis and general. The straight line x0 + k0 (T - T0) is an
    # integer, so it floors to itself only when the proven deviation lies in [0, 1): keep
    # exactly those (see PROVENANCE.md, R0 interpretation).
    want = {"axis": 200, "general": 300}
    got = {"axis": 0, "general": 0}
    while got["axis"] < want["axis"] or got["general"] < want["general"]:
        axis = got["axis"] < want["axis"]
        M = max(1, int(round(2 ** rng.uniform(0, 40))))
        Q = max(1, int(round(2 ** rng.uniform(4, 40))))
        r = M * 2.0 ** rng.uniform(30, 96 - math.log2(M))
        if r > 2.0 ** 95.5:
            continue
        if axis:
            a = -rand_int_near(rng, r)
            x = (a, 0) if rng.random() < 0.5 else (0, a)
        else:
            th = rng.uniform(math.pi * 1.05, math.pi * 1.45)   # third quadrant: pull is (+, +)
            x = (rand_int_near(rng, r * math.cos(th)), rand_int_near(rng, r * math.sin(th)))
        sp = rng.uniform(0, 0.95)
        if axis:
            k = (int(round(Q * sp * rng.choice([1, -1]))), 0) if x[1] == 0 else \
                (0, int(round(Q * sp * rng.choice([1, -1]))))
        else:
            psi = rng.uniform(0, 2 * math.pi)
            k = (int(round(Q * sp * math.cos(psi))), int(round(Q * sp * math.sin(psi))))
        null = False
        g = geo(M, Q, x, k, null)
        if g is None:
            continue
        dt = max(1, int(2.0 ** rng.uniform(0, 24)))
        try:
            res = g.query(dt)
            if res["at"] != "Free":
                continue
            kk, Z = g.solve(arb(Q * dt))
            X = g.X_at(kk, Z)
        except gj.Undecided:
            continue
        ok = True
        for c in range(2):
            line = x[c] + k[c] * dt
            if (x[c] == 0 and k[c] == 0):
                continue
            dev = X[c] - line
            if not (dev >= 0 and dev < 1):
                ok = False
        if not ok:
            continue
        t0 = rng.randint(-2 ** 40, 2 ** 40)
        kind = "axis" if axis else "general"
        got[kind] += 1
        cases.append(mk(f"R0-{len(cases):04d}", "R0", ["far-field-hop", kind], M, Q, t0, x, k,
                        False, [t0 + dt], straight_line=[S(x[0] + k[0] * dt), S(x[1] + k[1] * dt)]))
    return cases


