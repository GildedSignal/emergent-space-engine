# R1: radial infall and circular cases


def circular_anchor(rng, M, w, t, h_choice, sign, rot):
    """Exact circular timelike anchor: x0 = g (a0, b0), |(a0, b0)| = h (h a square),
    r = M w^2 h, k0 perpendicular with |k0| = t h and Q = t w h^(3/2), so |k|^2 r = M Q^2."""
    (a0, b0, h) = h_choice
    hs = math.isqrt(h)
    g = M * w * w
    x = (g * a0, g * b0)
    k = (-b0 * t * sign, a0 * t * sign)
    for _ in range(rot):
        x = (-x[1], x[0])
        k = (-k[1], k[0])
    Q = t * w * h * hs
    return Q, x, k


HCHOICES = [(1, 0, 1), (7, 24, 25), (24, 7, 25), (15, 20, 25), (20, 15, 25)]


def gen_R1(rng):
    cases = []
    # radial: from rest in the coordinates, at rest in the flow, inward, outward, bound, null
    kinds = {}
    while len(cases) < 300:
        null = len(cases) % 5 == 4
        M, Q, x, k, g = radial_anchor(rng, null)
        kind = g.info["kind"]
        if kinds.get(kind, 0) >= 80:
            continue
        kinds[kind] = kinds.get(kind, 0) + 1
        dt = draw_dt(rng, time_scale(g))
        t0 = rng.randint(-2 ** 40, 2 ** 40)
        cases.append(mk(f"R1-{len(cases):04d}", "R1", ["radial", kind], M, Q, t0, x, k, null, [t0 + dt]))
    # at rest in the flow (E = 1): r0 = 2M j^2 on an axis, beta = -Q/j integer when j | Q
    for i in range(40):
        M = max(1, int(round(2 ** rng.uniform(0, 70))))
        j = rng.randint(2, 2 ** 6)
        r0 = 2 * M * j * j
        if r0 > LIM:
            continue
        Q = j * max(1, int(round(2 ** rng.uniform(0, 30))))
        if Q > 2 ** 40:
            continue
        s = rng.choice([(1, 0), (0, 1), (-1, 0), (0, -1)])
        x = (r0 * s[0], r0 * s[1])
        k = (-(Q // j) * s[0], -(Q // j) * s[1])
        g = geo(M, Q, x, k, False)
        if g is None:
            continue
        dt = draw_dt(rng, time_scale(g))
        cases.append(mk(f"R1-{len(cases):04d}", "R1", ["radial", "flow-rest"], M, Q, 0, x, k, False, [dt]))
    # exact circular orbits (stable and unstable)
    n = 0
    while n < 200:
        M = max(1, int(round(2 ** rng.uniform(0, 60))))
        hc = rng.choice(HCHOICES)
        w = rng.randint(1, 2 ** 10)
        if w * w * hc[2] <= 3:
            continue
        t = rng.randint(1, 2 ** 12)
        Q, x, k = circular_anchor(rng, M, w, t, hc, rng.choice([1, -1]), rng.randint(0, 3))
        if Q > 2 ** 40 or max(abs(x[0]), abs(x[1])) > LIM:
            continue
        g = geo(M, Q, x, k, False)
        if g is None or g.chart != "circular":
            continue
        dt = draw_dt(rng, time_scale(g))
        t0 = rng.randint(-2 ** 40, 2 ** 40)
        rM = w * w * hc[2]
        cases.append(mk(f"R1-{len(cases):04d}", "R1", ["circular", "stable" if rM > 6 else "unstable"],
                        M, Q, t0, x, k, False, [t0 + dt]))
        n += 1
    return cases


