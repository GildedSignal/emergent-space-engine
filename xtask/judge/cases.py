def S(v):
    return str(int(v))


def mk(cid, rung, cls, M, Q, t0, x, k, null, Ts, **extra):
    d = {"id": cid, "rung": rung, "class": cls, "M": S(M), "Q": S(Q), "t0": S(t0),
         "x": [S(x[0]), S(x[1])], "k": [S(k[0]), S(k[1])],
         "motion": "null" if null else "timelike", "T": [S(T) for T in Ts]}
    d.update(extra)
    return d


def to_case_ints(c):
    return {"id": c["id"], "M": int(c["M"]), "Q": int(c["Q"]), "t0": int(c["t0"]),
            "x": [int(v) for v in c["x"]], "k": [int(v) for v in c["k"]],
            "motion": c["motion"], "T": [int(v) for v in c["T"]]}


def write(path, cases):
    with gzip.open(path, "wt") as f:
        for c in cases:
            f.write(json.dumps(c, separators=(",", ":")) + "\n")


