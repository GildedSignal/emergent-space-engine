def convergent_scale(f, qmax, tol):
    """Smallest continued-fraction denominator q <= qmax with |q f - p| < tol (f an arb in
    (0, 1)); returns (q, p) or None."""
    ctx.prec = 1024
    x = f
    h0, h1 = 0, 1       # numerators p
    k0, k1 = 1, 0       # denominators q
    for _ in range(200):
        a = int(x.mid().floor().unique_fmpz())
        h0, h1 = h1, a * h1 + h0
        k0, k1 = k1, a * k1 + k0
        if k1 > qmax:
            return None
        err = abs(k1 * f - h1)
        if err < tol and not err.contains(0):
            return k1, h1
        frac = x - a
        if not frac > 0:
            return None
        x = 1 / frac
    return None


def base_for_chart(rng, chart):
    """A small base anchor in the requested chart: (M, Q, x, k, null, g, dt)."""
    while True:
        if chart == "circular":
            M = max(1, int(round(2 ** rng.uniform(0, 20))))
            hc = rng.choice(HCHOICES)
            w = rng.randint(1, 2 ** 5)
            if w * w * hc[2] <= 3:
                continue
            t = rng.randint(1, 2 ** 12)
            Q, x, k = circular_anchor(rng, M, w, t, hc, rng.choice([1, -1]), rng.randint(0, 3))
            null = False
            if Q > 2 ** 40:
                continue
        elif chart == "radial":
            M, Q, x, k, g0 = radial_anchor_small(rng)
            null = False
        else:
            null = chart == "null"
            M, Q, x, k, g0 = pinned_anchor(rng, null, lm_range=(0, 20), rmax_log=48)
        g = geo(M, Q, x, k, null, 512)
        if g is None:
            continue
        ch = "null" if null else g.chart
        if ch != chart:
            continue
        ts = time_scale(g)
        dt = draw_dt(rng, min(ts, 2.0 ** 30))
        try:
            res = g.query(dt)
        except gj.Undecided:
            continue
        if res["at"] != "Free":
            continue
        return M, Q, x, k, null, g, dt


def radial_anchor_small(rng):
    while True:
        M, Q, x, k, g = radial_anchor(rng, False)
        if M <= 2 ** 20 and max(abs(x[0]), abs(x[1])) <= 2 ** 48:
            return M, Q, x, k, g


def gen_R4(rng, per_chart=200):
    cases = []
    for chart in ("radial", "circular", "three-root", "one-root", "null"):
        n = 0
        while n < per_chart:
            M, Q, x, k, null, g, dt = base_for_chart(rng, chart)
            kk, Z = g.solve(arb(Q * dt))
            X = g.X_at(kk, Z)
            c = rng.randint(0, 1)
            if (x[c] == 0 and chart == "radial") or not X[c].is_finite():
                c = 1 - c
            xc = X[c]
            if xc.is_exact() and xc == 0:
                continue
            f = xc - xc.mid().floor()
            mag = max(abs(x[0]), abs(x[1]), int(abs(float(X[0].mid()))) + 1, int(abs(float(X[1].mid()))) + 1)
            qmax = min(TWO80 // M, LIM // (mag + 1), TWO80 // dt)
            cv = convergent_scale(f, qmax, arb(2) ** -40)
            if cv is None:
                continue
            lam, _ = cv
            if lam < 2:
                continue
            t0 = rng.randint(-2 ** 60, 2 ** 60)
            Ms, xs = lam * M, (lam * x[0], lam * x[1])
            cases.append(mk(f"R4-{len(cases):05d}", "R4", ["near-integer", chart, g.info.get("kind")],
                            Ms, Q, t0, xs, k, null, [t0 + lam * dt],
                            construction={"base": {"M": S(M), "x": [S(x[0]), S(x[1])], "dt": S(dt)},
                                          "scale": S(lam), "coord": c}))
            n += 1
    return cases


