"""Regenerate src/tables.rs with Decimal (precision 90); no binary-float rounding decisions.
Every entry is round-half-up of the exact value times the stated power of two."""
from decimal import Decimal as D, localcontext, ROUND_HALF_UP
from pathlib import Path
with localcontext() as ctx:
    ctx.prec = 90
    q = lambda x, bits: int((x * D(2) ** bits).to_integral_value(rounding=ROUND_HALF_UP))
    # pi by Machin's formula, arctangent by its Taylor series (|x| <= 1/5 here, and <= 1/16 below).
    def atan_small(x):
        s, t, k = D(0), x, 0
        while abs(t) > D('1e-88'):
            s += t / (2 * k + 1)
            t *= -x * x
            k += 1
        return s
    pi = 16 * atan_small(D(1) / 5) - 4 * atan_small(D(1) / 239)
    def atan(x):  # x in [0, 1]: atan(x) = 2 atan(x / (1 + sqrt(1 + x^2)))
        return 2 * atan_small(x / (1 + (1 + x * x).sqrt())) if x > D('0.2') else atan_small(x)
    edges = [q(D(2) ** (-D(j) / 16), 62) for j in range(17)]
    # Gauss-Legendre, four nodes: roots of P4, Newton from decimal seeds to 85 digits.
    nodes, weights = [], []
    for seed in ['.34', '.86']:
        z = D(seed)
        for _ in range(60):
            p0, p1 = D(1), z
            for n in range(2, 5):
                p0, p1 = p1, ((2 * n - 1) * z * p1 - (n - 1) * p0) / n
            dp = 4 * (z * p1 - p0) / (z * z - 1)
            dz = p1 / dp
            z -= dz
            if abs(dz) < D('1e-85'):
                break
        nodes.append(z)
        weights.append(2 / ((1 - z * z) * dp * dp))
    out = '// Generated by tests/tables.py: Decimal, precision 90, round half up.\n'
    out += '/// 2^(-j/16) in Q62, j = 0..=16: the band edges within one octave.\n'
    out += 'pub const EDGE: [i128; 17] = ' + repr(edges) + ';\n'
    out += '/// pi in Q61.\n'
    out += 'pub const PI: i128 = ' + str(q(pi, 61)) + ';\n'
    out += '/// Four-point Gauss-Legendre on [-1, 1]: nodes +-X[i] with weights W[i], Q62.\n'
    out += 'pub const X: [i128; 2] = ' + repr([q(z, 62) for z in nodes]) + ';\n'
    out += 'pub const W: [i128; 2] = ' + repr([q(w, 62) for w in weights]) + ';\n'
    out += '/// atan(j/16) in Q62, j = 0..=16.\n'
    out += 'pub const ATAN: [i128; 17] = ' + repr([q(atan(D(j) / 16), 62) for j in range(17)]) + ';\n'
    out += '/// 1/(2k+1) in Q62, k = 0..=6: the arctangent series.\n'
    out += 'pub const ODD: [i128; 7] = ' + repr([q(D(1) / (2 * k + 1), 62) for k in range(7)]) + ';\n'
    out += '/// 1/((2k)(2k+1)) in Q62, k = 1..=13: the nested sine series.\n'
    out += 'pub const SINE: [i128; 13] = ' + repr([q(D(1) / ((2 * k) * (2 * k + 1)), 62) for k in range(1, 14)]) + ';\n'
    Path(__file__).resolve().parents[1].joinpath('src/tables.rs').write_text(out)
