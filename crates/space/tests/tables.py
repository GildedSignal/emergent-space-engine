"""Regenerate canonical tables with Decimal; no binary-float rounding decisions."""
from decimal import Decimal as D, localcontext, ROUND_HALF_UP
from pathlib import Path
with localcontext() as ctx:
 ctx.prec=90
 q=lambda x:int((x*D(2)**30).to_integral_value(rounding=ROUND_HALF_UP))
 edges=[q(D(2)**(-D(j)/16)) for j in range(17)]
 centers=[q(D(2)**(-(D(j)+D('.5'))/16)) for j in range(16)]
 # Legendre degree 8, decimal seeds only; Newton convergence to 85 digits.
 nodes=[];weights=[]
 for seed in ['.18','.52','.80','.96']:
  z=D(seed)
  for _ in range(50):
   p0,p1=D(1),z
   for n in range(2,9): p0,p1=p1,((2*n-1)*z*p1-(n-1)*p0)/n
   dp=8*(z*p1-p0)/(z*z-1)
   dz=p1/dp;z-=dz
   if abs(dz)<D('1e-85'):break
  weight=2/((1-z*z)*dp*dp)
  nodes.extend([-z,z]);weights.extend([weight,weight])
 pairs=sorted(zip(nodes,weights))
 out='// Generated by tests/tables.py: Decimal, precision 90, nearest/ties away.\n'
 out+='pub const EDGES: [i64;17] = '+repr(edges)+';\n'
 out+='pub const CENTERS: [i64;16] = '+repr(centers)+';\n'
 out+='pub const NODES: [i64;8] = '+repr([q(z) for z,w in pairs])+';\n'
 out+='pub const WEIGHTS: [i64;8] = '+repr([q(w) for z,w in pairs])+';\n'
 Path(__file__).resolve().parents[1].joinpath('src/bands.rs').write_text(out)
