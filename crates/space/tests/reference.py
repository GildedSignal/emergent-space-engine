"""Generate independent fixtures from the supplied, checker-fixed float Binet code.
Run with Python/numpy, supplying the reference directory and output file.
No gate, sampler or reference implementation is modified.
"""
import sys, json, hashlib
from pathlib import Path
from decimal import Decimal, localcontext, ROUND_HALF_UP
ref=Path(sys.argv[1]).resolve()
sys.path.insert(0,str(ref))
import numpy as np
from rung import binet_run, BOUND, bound_EL, GLX, GLW
from oracle import bound_constants
cases=BOUND+[(20.,.5),(10.,.1),(100.,.7),(1000.,.4),(20.,.001),(7.9,.2)]
p,e,E,L=bound_EL(cases)
r=binet_run((1+e)/p,np.zeros(len(cases)),E,L,16,False,1,max_iter=1024,seq_cycles=1,trace_lanes=tuple(range(len(cases))))
rows=[]
for i,(pp,ee) in enumerate(cases):
 trace=np.asarray(r['trace'][i]).reshape(-1,16,2)
 h=(trace[:, -1, 0]-trace[:, 0, 0])*2/(GLX[-1]-GLX[0])
 tau=float(np.sum(h/2*np.sum(GLW[None,:]/(L[i]*trace[:,:,1]**2),axis=1)))
 rows.append(dict(tau=tau,p=pp,e=ee,phi=float(r['dphi'][i,0]),t=float(r['dt'][i,0]),u_peri=float(r['up'][i,0]),u_apo=float(r['ua'][i,0]),crossings=int(r['nc'][i,0]),bands=r['seq'][0][i]))
out=dict(provenance={f:hashlib.sha256((ref/f).read_bytes()).hexdigest() for f in ['rung.py','oracle.py','check.md']},rows=rows)
Path(sys.argv[2]).write_text(json.dumps(out,separators=(',',':'))+'\n')
# Rust fixture has no dependency on Python at test time.
rs='// Generated by reference.py; provenance is in reference.json.\n'
rs+='// (p, e, full angle, coordinate period, proper period, peri u, apo u, crossings)\n'
rs+='pub const REFERENCE: &[(f64,f64,f64,f64,f64,f64,f64,usize)] = &[\n'
for r in rows:
 rs+='    ('+', '.join(repr(r[k]) for k in ['p','e','phi','t','tau','u_peri','u_apo','crossings'])+'),\n'
rs+='];\n'
rs+='pub const SEQUENCES: &[&[i32]] = &[\n'
for row in rows: rs+='    &'+repr(row['bands'])+',\n'
rs+='];\n'
Path(sys.argv[2]).with_suffix('.rs').write_text(rs)
with localcontext() as ctx:
 ctx.prec=90
 q=lambda x:int((x*Decimal(2)**30).to_integral_value(rounding=ROUND_HALF_UP))
 edges=[q(Decimal(2)**(-Decimal(j)/16)) for j in range(17)]
 centers=[q(Decimal(2)**(-(Decimal(j)+Decimal('.5'))/16)) for j in range(16)]
 print('EDGES',edges,'CENTERS',centers)
print('generated',len(rows),'cases')
