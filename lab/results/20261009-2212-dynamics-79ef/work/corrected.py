#!/usr/bin/env python3
"""Corrected encounter-stream statistics (supersedes analysis.py's naive branching).
Within-body conditional excess b(tau): removes per-body rate heterogeneity.
Control: per-body Poisson resample at each body's own rate (must give ~0).
Also: lambda(t) power-law fits and the (e, lambda) collapse across runs.
Usage: python3 corrected.py   (needs *_ev.tsv / *_out.tsv regenerated by belt, or gunzip *_ev.tsv.gz)
Prints the numbers quoted in dossier.md; writes corrected.json."""
import math, os, json
import numpy as np
ORBIT=2*math.pi; N=600; HERE=os.path.dirname(os.path.abspath(__file__))+"/"
res={}
for tag in ["r1","r2","r3","hot","w10","m8","w30"]:
    if not os.path.exists(HERE+f"{tag}_ev.tsv"): continue
    d=np.loadtxt(HERE+f"{tag}_ev.tsv",skiprows=2); o=np.loadtxt(HERE+f"{tag}_out.tsv",skiprows=1)
    t=o[:,0]/ORBIT; e=o[:,1]
    edges=np.arange(0,t[-1]+1,1.0); h,_=np.histogram(d[:,0]/ORBIT,bins=edges); lam=h/N
    m=(t>=10); ti=np.minimum(t[m].astype(int),len(lam)-1)
    a_lam=np.polyfit(np.log(t[m]),np.log(np.maximum(lam[ti],1e-6)),1)[0]
    b_e=np.polyfit(np.log(t[m]),np.log(e[m]),1)[0]
    res[tag]=dict(lam_exp=float(-a_lam), e_exp=float(b_e), e_end=float(e[-1]))
# collapse (non-hot)
xs=[];ys=[];lab=[]
for tag in res:
    if not os.path.exists(HERE+f"{tag}_out.tsv"): continue
    o=np.loadtxt(HERE+f"{tag}_out.tsv",skiprows=1); d=np.loadtxt(HERE+f"{tag}_ev.tsv",skiprows=2)
    t=o[:,0]/ORBIT; e=o[:,1]
    eb=np.arange(5,t[-1],5)
    for k in range(len(eb)):
        mm=(d[:,0]/ORBIT>=eb[k]-5)&(d[:,0]/ORBIT<eb[k]); L=mm.sum()/(N*5)
        E=np.interp(eb[k],t,e)
        if 0.03<=E<=0.35 and L>1e-4: xs.append(E);ys.append(L);lab.append(tag)
xs=np.array(xs);ys=np.array(ys); mh=np.array([l!="hot" for l in lab])
g,logC=np.polyfit(np.log(xs[mh]),np.log(ys[mh]),1)
res["collapse"]=dict(C=float(math.exp(logC)),g=float(g),
    resid_dex={t:float(np.mean(np.log10(ys[np.array(lab)==t]/(math.exp(logC)*xs[np.array(lab)==t]**g)))) for t in set(lab)})
# within-body branching + Poisson control on baseline seeds
for tag in ["r1","r2","r3"]:
    if not os.path.exists(HERE+f"{tag}_ev.tsv"): continue
    d=np.loadtxt(HERE+f"{tag}_ev.tsv",skiprows=2)
    m=(d[:,0]/ORBIT>=50)&(d[:,0]/ORBIT<150); dt=d[m]
    streams={}; cnt={}
    for k in (1,2):
        for b,tt in zip(dt[:,k].astype(int),dt[:,0]):
            streams.setdefault(b,[]).append(tt); cnt[b]=cnt.get(b,0)+1
    c=np.array(list(cnt.values()),float); lam_i=c/100.0
    tau=1.0; num=den=0.0
    for b,tsl in streams.items():
        ts=np.sort(np.array(tsl)); li=cnt[b]/100.0
        idx=np.searchsorted(ts,ts+tau*ORBIT,side='right')-np.arange(len(ts))-1
        num+=idx.sum(); den+=len(ts)*li*tau
    b_w=num/den-1
    rng=np.random.default_rng(5); bs=[]
    for rep in range(50):
        n2=d2=0.0
        for b,tsl in streams.items():
            li=cnt[b]/100.0; n=rng.poisson(li*100)
            ts2=np.sort(rng.uniform(50*ORBIT,150*ORBIT,n))
            idx=np.searchsorted(ts2,ts2+tau*ORBIT,side='right')-np.arange(n)-1
            n2+=idx.sum(); d2+=n*li*tau
        bs.append(n2/d2-1)
    res[tag]["within_body_b_1orb"]=float(b_w)
    res[tag]["poisson_control"]=float(np.mean(bs)); res[tag]["poisson_control_sd"]=float(np.std(bs))
    res[tag]["lam_i_med"]=float(np.median(lam_i)); res[tag]["lam_i_p99_over_med"]=float(np.percentile(lam_i,99)/np.median(lam_i))
    res[tag]["lam_i_max_over_med"]=float(lam_i.max()/np.median(lam_i))
json.dump(res,open(HERE+"corrected.json","w"),indent=1)
print(json.dumps(res,indent=1))
