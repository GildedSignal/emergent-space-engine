#!/usr/bin/env bash
# Regenerates every dossier number from shipped code + work/patch.diff, ~10 min on 8 vCPU, cold.
#
# NO SHARED TARGET CACHE, ever: git archive stamps files with the commit's mtime, so a cache
# copied in (the prior window's workflow) can be newer than the sources and cargo silently links
# another tree's objects. Every snapshot here builds cold in its own target; the clamp-only
# reference build is the control that catches any such drift (its digests are the record's).
set -euo pipefail
SELF=$(readlink -f "$0")
cd "$(git rev-parse --show-toplevel)"
T="$PWD"
R=lab/results/20261014-1010-second-20261014-0450-quant-1845-0b85
# Absolute, so `git apply` inside snap()'s subshell (cwd = the snapshot dir) finds it.
PATCH="$T/$R/work/patch.diff"
# If the patch is absent (run.sh once saved it after regen's first invocation), rebuild it
# from the base64 copy embedded at the tail of this script: regen never depends on
# publish ordering, and one missing file can never again fail the whole record with 128.
if [ ! -s "$PATCH" ]; then
  mkdir -p "$(dirname "$PATCH")"
  sed -n '/^__PATCH_B64__$/,/^__PATCH_END__$/p' "$SELF" | sed '1d;$d' | base64 -d > "$PATCH"
fi

snap() { # <dir> <commit> [patch-abs-path]
  rm -rf "$1" && mkdir -p "$1"
  git archive "$2" | tar -x -C "$1"
  [ -n "${3:-}" ] && (cd "$1" && git apply "$3")
  find "$1" -name '*.rs' -exec touch {} +
  find "$1" -name Cargo.toml -exec touch {} +
}
run() { # <xtask> <out> <seed> <rtf> <members> [warm]
  local xt=$1 out=$2 seed=$3 rtf=$4 m=$5
  if [ -n "${6:-}" ]; then export ES_IMP_WARM=1; else unset ES_IMP_WARM; fi
  ES_MEMBERS=1000000 "$xt" universe --bench --seed "$seed" --rtf "$rtf" --seconds 8 --members "$m" > "$out" 2> "${out%.json}.err"
}

SNAP=$(mktemp -d /tmp/regen-0b85-XXXXXX)
trap 'rm -rf "$SNAP"' EXIT
mkdir -p "$SNAP/out"

# 1. HEAD + this patch (the warm-start gallop, ES_IMP_WARM-gated), prof: the five A/B arms.
snap "$SNAP/head" HEAD "$PATCH"
(cd "$SNAP/head" && CARGO_TARGET_DIR="$SNAP/head/target" cargo build --release -p xtask --features emergent-universe/prof 2>&1 | tail -1)
XT="$SNAP/head/target/release/xtask"
for arm in "m4000-s3 3 1 4000" "m1500-s3 3 1 1500" "m4000-s7 7 1 4000" "m400-s3-f 3 100 400" "m16000-s3 3 1 16000"; do
  set -- $arm
  run "$XT" "$SNAP/out/$1-off.json" "$2" "$3" "$4"
  run "$XT" "$SNAP/out/$1-on.json" "$2" "$3" "$4" warm
done

# 2. HEAD + patch, plain (prof off, warm on): the adoption identity. Pristine HEAD at m400
#    (inside the shipped clamp) cross-checks the patch changes nothing the clamp-only record
#    does not also show; m4000's identity reference is the clamp-only build (step 4).
snap "$SNAP/plain" HEAD "$PATCH"
(cd "$SNAP/plain" && CARGO_TARGET_DIR="$SNAP/plain/target" cargo build --release -p xtask 2>&1 | tail -1)
run "$SNAP/plain/target/release/xtask" "$SNAP/out/m4000-s3-plain.json" 3 1 4000 warm
run "$SNAP/plain/target/release/xtask" "$SNAP/out/m1500-s3-plain.json" 3 1 1500 warm
run "$SNAP/plain/target/release/xtask" "$SNAP/out/m400-s3-plain.json" 3 1 400 warm
snap "$SNAP/pris" HEAD
(cd "$SNAP/pris" && CARGO_TARGET_DIR="$SNAP/pris/target" cargo build --release -p xtask 2>&1 | tail -1)
run "$SNAP/pris/target/release/xtask" "$SNAP/out/m400-s3-pristine.json" 3 1 400

# 3. The shipped-record reference: base 8498d1c8 (the prior run's recorded base) + ONLY the
#    members-clamp lift — the engine as shipped, arms unlocked. Its digests are the published
#    record's (2e97e580 / 7b33d0b8) and HEAD reproduces them (the ladder merge was
#    digest-preserving here).
snap "$SNAP/clamp" 8498d1c8
(cd "$SNAP/clamp" && python3 - <<'EOF'
from pathlib import Path
p = Path('xtask/src/universe/mod.rs'); s = p.read_text()
old = '"--members" => members = val("--members")?.parse::<u64>()?.clamp(4, 400),'
new = '"--members" => {\n                let hi = std::env::var("ES_MEMBERS").ok().and_then(|v| v.parse::<u64>().ok()).unwrap_or(400);\n                members = val("--members")?.parse::<u64>()?.clamp(4, hi);\n            }'
assert old in s; p.write_text(s.replace(old, new))
EOF
)
find "$SNAP/clamp" -name '*.rs' -exec touch {} +
(cd "$SNAP/clamp" && CARGO_TARGET_DIR="$SNAP/clamp/target" cargo build --release -p xtask 2>&1 | tail -1)
run "$SNAP/clamp/target/release/xtask" "$SNAP/out/clamp-m4000-s3.json" 3 1 4000
run "$SNAP/clamp/target/release/xtask" "$SNAP/out/clamp-m1500-s3.json" 3 1 1500

# 4. The prior run's own patch on that clean base: its record regenerates (kick ~252 µs, K_IMP
#    2064 — the premise this run's warm start deletes was real and reproducible).
git show origin/claude/lab-20261014-0450-quant-1845:lab/results/20261014-0450-quant-1845/work/patch.diff > "$SNAP/prior.patch"
snap "$SNAP/prior" 8498d1c8
(cd "$SNAP/prior" && git apply "$SNAP/prior.patch")
find "$SNAP/prior" -name '*.rs' -exec touch {} +
(cd "$SNAP/prior" && CARGO_TARGET_DIR="$SNAP/prior/target" cargo build --release -p xtask --features emergent-universe/prof 2>&1 | tail -1)
run "$SNAP/prior/target/release/xtask" "$SNAP/out/prior-m4000-s3-off.json" 3 1 4000

mkdir -p "$R/work"
cp "$SNAP"/out/*.json "$R/work/"
python3 "$R/work/table.py"
python3 - "$R/work" <<'EOF'
import json, sys, pathlib
W = pathlib.Path(sys.argv[1])
def dg(n): return json.load(open(W / f"{n}.json"))["digest"]
for a, b, what in [("clamp-m4000-s3", "m4000-s3-off", "HEAD warm-off == clamp-only shipped (m4000)"),
                   ("clamp-m4000-s3", "m4000-s3-on", "HEAD warm-ON == clamp-only shipped (m4000)"),
                   ("clamp-m4000-s3", "m4000-s3-plain", "plain warm-on == shipped (m4000)"),
                   ("clamp-m1500-s3", "m1500-s3-plain", "plain warm-on == shipped (m1500)"),
                   ("m400-s3-plain", "m400-s3-pristine", "patched plain == pristine HEAD (m400)"),
                   ("prior-m4000-s3-off", "m4000-s3-off", "prior patch base == this patch HEAD (m4000)")]:
    print(("IDENTICAL " if dg(a) == dg(b) else "DIFFER!!  ") + what, dg(a)[:16], dg(b)[:16])
EOF
exit 0
