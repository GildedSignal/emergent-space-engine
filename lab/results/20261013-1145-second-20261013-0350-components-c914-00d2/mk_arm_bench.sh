#!/bin/bash
# Build the standalone aarch64 division-floor bench from the PATCHED tree's
# crates/space/examples/div_bench.rs (run 20261013-0350-components-c914),
# extracting the kernels VERBATIM (no edits): Lcg, div_asm, pairs_4096
# (range A) and mul_hi, dm_excess, div_newton (range B). bench_div/bench_newton
# are replaced by a mode-dispatched harness (one variant per process, so QEMU
# can count one variant's guest instructions in isolation).
set -euo pipefail
SRC=crates/space/examples/div_bench.rs
OUT=${1:-crates/space/examples/div_floor_arm.rs}
A1=$(grep -n '^struct Lcg' $SRC | cut -d: -f1)
A2=$(grep -n '^fn pairs_4096' $SRC | cut -d: -f1)          # exclusive
B1=$(grep -n '^fn mul_hi' $SRC | cut -d: -f1)
B2=$(grep -n '^fn bench_newton' $SRC | cut -d: -f1)        # exclusive
{
  echo "// GENERATED by mk_arm_bench.sh — kernels verbatim from $SRC (do not edit)."
  echo "// Same operand shapes and quotient-chaining as div_bench's bench_div/bench_newton."
  echo "use std::time::Instant;"
  sed -n "${A1},$((A2-1))p" $SRC   # Lcg + div_asm (cfg(not(x86_64)) arm compiles here)
  BD=$(grep -n '^fn bench_div' $SRC | cut -d: -f1)
  sed -n "${A2},$((BD-1))p" $SRC   # pairs_4096
  sed -n "${B1},$((B2-1))p" $SRC   # mul_hi + dm_excess + div_newton
  cat <<'EOF'
// ---- harness (this run's own; measurement loops copied from bench_div) ----
fn step(n: &mut u128, d: &mut u64, q: u128) {
    *n = n.wrapping_mul(0x100000001b3).wrapping_add(q) | 1;
    *d = (d.wrapping_mul(6364136223846793005) ^ (q as u64) >> 23) % (1u64 << 62) | (1 << 20);
}
fn main() {
    let mode = std::env::args().nth(1).unwrap_or_else(|| "soft".into());
    let rounds: u64 = std::env::var("ROUNDS").ok().and_then(|s| s.parse().ok()).unwrap_or(2000);
    let pairs = pairs_4096();
    let total = rounds * pairs.len() as u64;
    let mut sink = 0u128;
    if mode != "none" {
        let t = Instant::now();
        let (mut n, mut d) = pairs[0];
        for _ in 0..total {
            let q = match mode.as_str() {
                "soft" => n / d as u128,
                "i128" => ((n as i128) / (d as i128)) as u128,
                "asm" => div_asm(n, d),
                "newton" => div_newton(n, d),
                _ => unreachable!(),
            };
            sink ^= q;
            step(&mut n, &mut d, q);
        }
        let per = t.elapsed().as_nanos() as f64 / total as f64;
        println!("arm-div[{}] {:.2} ns/div ({} divs, sink {})", mode, per, total, sink & 1);
    } else {
        let (mut n, mut d) = pairs[0];
        for _ in 0..total {
            step(&mut n, &mut d, 0);
            sink ^= n;
        }
        println!("arm-div[none] {} steps, sink {}", total, sink & 1);
    }
    // Exactness sweep on all pairs + the adversarial nine (verbatim shapes).
    if mode == "newton" || mode == "asm" {
        let mut bad = 0u64;
        for &(n, d) in &pairs {
            let got = if mode == "newton" { div_newton(n, d) } else { div_asm(n, d) };
            if got != n / d as u128 { bad += 1; }
        }
        println!("arm-div[{}] mismatches on {} pairs: {}", mode, pairs.len(), bad);
    }
}
EOF
} > $OUT
echo "wrote $OUT ($(grep -c . $OUT) lines)"
