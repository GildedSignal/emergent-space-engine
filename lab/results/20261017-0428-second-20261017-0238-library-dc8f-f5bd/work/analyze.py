#!/usr/bin/env python3
"""The debt-vs-horizon curve from the long OFF/ARM traces, the fence-quantum table, and k*.

Inputs (regenerated by regen.sh): work/trace_off.txt, work/trace_arm.txt (ES_TRACE dumps of
the 477 deleted bodies' position angles at matched log-spaced horizons), work/ids.txt, the
end states work/long_{off,arm}_states.csv, and the bench flight's es_bench line.
"""
import math, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
RUN = os.path.dirname(HERE)

def load_trace(path):
    """horizon -> {id: angle_deg}; the last dump <= each threshold wins."""
    out = []
    for ln in open(path):
        p = ln.split()
        if p[0] != 'T':
            continue
        t = float(p[2])
        angs = {}
        for tok in p[3:]:
            i, a = tok.split(':')
            try:
                angs[int(i)] = float(a)
            except ValueError:
                pass
        out.append((t, angs))
    return out

def wrap(x):
    return (x + 180.0) % 360.0 - 180.0

TRACE_OFF = os.environ.get('TRACE_OFF', os.path.join(HERE, 'trace_off.txt'))
TRACE_ARM = os.environ.get('TRACE_ARM', os.path.join(HERE, 'trace_arm.txt'))
LONG_OFF = os.environ.get('LONG_OFF', os.path.join(HERE, 'long_off_states.csv'))
LONG_ARM = os.environ.get('LONG_ARM', os.path.join(HERE, 'long_arm_states.csv'))
print(f"# traces: {os.path.basename(TRACE_OFF)} / {os.path.basename(TRACE_ARM)}")
off = load_trace(TRACE_OFF)
arm = load_trace(TRACE_ARM)
# population split by doll, from the 11,000-gs arm end states (the traced set is fixed)
doll_of = {}
for ln in open(os.path.join(HERE, 'states_11000_arm.csv')):
    p = ln.split()
    if p[0] == 'B':
        doll_of[int(p[1])] = p[2]
ids = [int(x) for x in open(os.path.join(HERE, 'ids.txt')).read().split()]
ids_set = set(ids)
insitu = [i for i in ids if doll_of.get(i) == '2']
belt = [i for i in ids if doll_of.get(i) == '0']
giant = [i for i in ids if doll_of.get(i) == '3']

# ---- the debt curve -------------------------------------------------------------------
print("== the debt: |angle(arm) - angle(OFF)| of the deleted set at matched horizons ==")
print("   horizon_gs   n   max_deg    p50_deg   |  in-situ max   belt max  | law fit so far")
rows = []
off_map = {round(t, 1): a for t, a in off}
for t, aa in arm:
    oo = None
    for tt, oang in off:
        if abs(tt - t) < max(1.0, t * 2e-3):
            oo = oang
            break
    if oo is None:
        continue
    common = [i for i in ids if i in aa and i in oo]
    ds = {i: abs(wrap(aa[i] - oo[i])) for i in common}
    ins = sorted(ds[i] for i in insitu if i in ds)
    blt = sorted(ds[i] for i in belt if i in ds)
    allx = sorted(ds.values())
    med = allx[len(allx) // 2]
    mx = allx[-1]
    rows.append((t, len(common), mx, med, ins[-1] if ins else float('nan'), blt[-1] if blt else float('nan')))
    print(f"  {t:11.0f} {len(common):4d} {mx:9.3e} {med:9.3e} | {ins[-1] if ins else 0:11.3e} {blt[-1] if blt else 0:10.3e}")

# ---- the law: fit max-debt vs horizon on the last N points ----------------------------
def fit(xs, ys):
    n = len(xs)
    sx = sum(xs); sy = sum(ys); sxx = sum(x * x for x in xs); sxy = sum(x * y for x, y in zip(xs, ys))
    b = (n * sxy - sx * sy) / (n * sxx - sx * sx)
    a = (sy - b * sx) / n
    return a, b

lx = [math.log10(t) for t, n, mx, med, i, b in rows if mx > 0]
ly = [math.log10(mx) for t, n, mx, med, i, b in rows if mx > 0]
for frac in (0.5, 0.75):
    k = max(2, int(len(lx) * frac))
    a, b = fit(lx[-k:], ly[-k:])
    print(f"fit on last {k}/{len(lx)} points: max_debt ~ t^{b:.2f}   (10^{a:.1f} deg at t=1 gs)")

# local slope per octave, last few octaves
print("local exponent (last 8 intervals):", end="")
for j in range(max(1, len(rows) - 8), len(rows)):
    t0, _, m0, *_ = rows[j - 1]
    t1, _, m1, *_ = rows[j]
    if m0 > 0 and m1 > 0:
        print(f" {math.log(m1 / m0) / math.log(t1 / t0):.2f}", end="")
print()

# ---- the fence quanta (published words) ------------------------------------------------
Q_TUBE = 360.0 / 2 ** 32
print(f"\n== the fence quanta, in degrees (shipped words) ==")
print(f"  tube periapsis-angle grid (32 bits, docs/law.md 'the periapsis angle (32 bits)'): {Q_TUBE:.3e}")
print(f"  readout position word 2^lexp/r at r (deleted in-situ, from the dump): 2.5e-17 .. 5.6e-17")
print(f"  velocity word 2^vexp/v (the kick grid's quantum):                    7.1e-17 .. 1.5e-16")
lmed_x = [math.log10(t) for t, n, mx, med, i, b in rows if med > 0]
lmed_y = [math.log10(med) for t, n, mx, med, i, b in rows if med > 0]
for frac, (xs, ys), lab in ((0.5, (lmed_x, lmed_y), 'median'), (0.5, (lx, ly), 'max')):
    k = max(2, int(len(xs) * frac))
    a, b = fit(xs[-k:], ys[-k:])
    print(f"fit {lab} on last {k}/{len(xs)}: debt ~ t^{b:.2f}")
STREAM = 3.55e-5  # ev/B/gs, a9d7 gold (the belt's carried-kick cadence)
A1, D1 = 2.6e-4, 5400.0
A2, D2 = 1.2e-3, 11000.0
p2 = math.log(A2 / A1) / math.log(D2 / D1)
print(f"\n== k* (re-kick interval, carried kicks at the belt cadence {STREAM}/B/gs) for candidate bars q ==")
def tstar_meas(q):
    """T* by log-log interpolation of the MEASURED max-debt curve (extrapolates the last octave's slope)."""
    if q <= rows[0][2]:
        return rows[0][0] * (q / rows[0][2]) ** (1.0 / 2.15)
    for j in range(1, len(rows)):
        if q <= rows[j][2]:
            t0, m0 = rows[j - 1][0], rows[j - 1][2]
            t1, m1 = rows[j][0], rows[j][2]
            return t0 * (t1 / t0) ** (math.log(q / m0) / math.log(m1 / m0))
    t0, m0 = rows[-1][0], rows[-1][2]
    _, b = fit([math.log10(r[0]) for r in rows[-8:]], [math.log10(r[2]) for r in rows[-8:]])
    return t0 * (q / m0) ** (1.0 / max(b, 0.5))
def tstar(q, law):
    if law == 'linear':
        return q / (A2 / D2)
    return D1 * (q / A1) ** (1.0 / p2)
print("   q (deg)     T* measured   k* meas |  T* power t^2.15 (dead)  k* power")
for q in (Q_TUBE, 1e-6, 1e-3, 1e-2, 0.1, 1.0, 30.0):
    tm = tstar_meas(q)
    tp = tstar(q, 'power')
    print(f"  {q:9.3e}  {tm:11.3g} gs  {math.log2(max(tm * STREAM, 1e-300)):6.1f} |  {tp:11.4g} gs  {math.log2(max(tp * STREAM, 1e-300)):6.1f}")
# ---- the record's own probe, reproduced: end-state |dA| at exactly 5,400 and 11,000 gs ----
print("\n== the published probe reproduced (end states at the flight's own final tick) ==")
for tag in ('5400', '11000'):
    o = {}
    a = {}
    for side, d in (('off', o), ('arm', a)):
        for ln in open(os.path.join(HERE, f'states_{tag}_{side}.csv')):
            p = ln.split()
            if p[0] == 'B':
                d[p[1]] = p
    ins = [i for i in a if i in o and doll_of.get(int(i)) == '2' and a[i][4] == '0' and a[i][5] == '1']
    blt = [i for i in a if i in o and doll_of.get(int(i)) == '0' and a[i][4] == '0' and a[i][5] == '1']
    ds = sorted(abs(wrap(float(a[i][8]) - float(o[i][8]))) for i in ins)
    db = sorted(abs(wrap(float(a[i][8]) - float(o[i][8]))) for i in blt)
    print(f"  {tag} gs: deleted in-situ n={len(ins)} max |dA| = {ds[-1]:.3e} deg (published 2.6e-4 @{tag}); belt n={len(db)} max = {db[-1]:.3e}")
# ---- spared-set bit-identity at the end states -----------------------------------------
def end_states(path):
    B, fleet = [], set()
    for ln in open(path):
        p = ln.split()
        if p[0] == 'F':
            fleet.add(p[1])
        elif p[0] == 'B':
            B.append(p)
    return {p[1]: p for p in B}, fleet
def end_game_s(path):
    """The flight's final game-s from its log ('game N s after ...'); None if absent."""
    try:
        for ln in open(path):
            m = re.search(r'game ([0-9.,]+) s after', ln)
            if m:
                return float(m.group(1).replace(',', ''))
    except OSError:
        pass
    return None
g_off = end_game_s(os.environ.get('FLIGHT_OFF', os.path.join(RUN, 'flights', 'long_off.txt')))
g_arm = end_game_s(os.environ.get('FLIGHT_ARM', os.path.join(RUN, 'flights', 'long_arm.txt')))
tick_mismatch = g_off is not None and g_arm is not None and abs(g_off - g_arm) > 1.0
if tick_mismatch:
    print(f"\n== spared check SKIPPED: the arms stopped at different ticks ({g_off:.0f} vs {g_arm:.0f} gs) ==")
have_states = os.path.exists(LONG_OFF) and os.path.exists(LONG_ARM)
if not have_states:
    print("\n== end states not present; skipped ==")
Bo, fo = end_states(LONG_OFF) if have_states else ({}, set())
Ba, fa = end_states(LONG_ARM) if have_states else ({}, set())
spared = [i for i in Bo if i in Ba and Bo[i][3] == 's' and i not in fa and Bo[i][4] != '0' and Ba[i][4] != '0']
diff = [i for i in spared if Bo[i][8] != Ba[i][8]]
del_now = [i for i in Bo if i in Ba and Ba[i][4] == '0' and Bo[i][3] == 's' and i not in fa and Ba[i][5] == '1']
if have_states and not tick_mismatch:
    print(f"\n== spared set at the final tick: {len(spared)} non-fleet ships kept in both; angle mismatches (6-decimal print): {len(diff)} {diff[:6]}")
    print(f"== deleted in the arm at the final tick: {len(del_now)} (the launch set was {len(ids)}); late joins: {sorted(set(del_now) - ids_set)[:8]}")

# ---- verdict -----------------------------------------------------------------------------
print("\n== verdict ==")
last = rows[-1]
pw = 2.6e-4 * (last[0] / 5400) ** 2.15
lin = 1.2e-3 * last[0] / 11000
print(f"  power t^2.15 predicted {pw:.3g} deg ({pw / last[2]:.0f}x the measured); linear-from-11k predicted {lin:.3g} ({last[2] / lin:.0f}x under) -> both dead; no saturation (still rising, local ~t^1.0-1.6)")
print(f"  k* (belt cadence) at every bar <= 1 deg: <= 2^{math.log2(max(tstar_meas(1.0), 1e-9) * 3.55e-5):.1f}; the 2^10-2^12 band's lower edge (T*=2.9e7 gs) extrapolates to a bar of ~70 deg on the measured curve")
