import re, glob, os

# ---- (A) the 355-core row, from 1a29's quoted numbers -------------------------
# 1a29: "sound wholesale = n-1 = 355 cores per 10^4-cell occupancy at 1 us/eval,
# 1 kick/body/interval on the checker's 28141.5-s clock".
N_BODIES, N_CELL, EVAL_S, INTERVAL_S = 1e9, 1e4, 1e-6, 28141.5
wholesale = N_BODIES / INTERVAL_S * (N_CELL - 1) * EVAL_S
print(f"(A) wholesale row recomputed  = {wholesale:.1f} cores   [1a29 quote: 355]")
assert abs(wholesale - 355.3) < 0.5
# Unit fact this pins: the row is (n-1) evals per kick TO ONE BODY, i.e. per
# pair-TOUCH — the divisor for a per-pair epoch must be touches, not cell kicks.

# ---- (B) the divisor, both ways -----------------------------------------------
E_PAIR = 1024                      # 1176's own dial: "E_pair = 1,024 touches"
N_REPLICA = 2000                   # 1176's make_belt cell
E_CELL = (N_REPLICA / 2) * E_PAIR  # their conversion
print(f"\n(B) row at E_pair={E_PAIR}: e828 355/E_pair = {355/E_PAIR:.3f} cores")
print(f"    row at E_cell={E_CELL:.3e}: 1176 355/E_cell = {355/E_CELL:.2e} cores"
      f"   [their quote: 3.5e-4]")
print(f"    understatement factor n/2 = {N_REPLICA/2:.0f} (their cell), "
      f"{N_CELL/2:.0f} (the occupancy the 355 is priced at)")
# Per cell kick, ONE body is kicked -> its n-1 pairs are touched; each comes up
# for re-decision with prob 1/E_pair. Re-arms per cell kick = (n-1)/E_pair,
# independent of how the per-pair period is counted (E_pair touches =
# (n/2)E_pair cell kicks for one pair, but n(n-1)/2 pairs share those kicks).
print(f"    re-arms per cell kick = (n-1)/E_pair = {(N_CELL-1)/E_PAIR:.2f}"
      f"  -> row {wholesale/E_PAIR:.3f} cores; divisor is E_pair at ANY n")

# ---- (C) the belt-real coupling r ---------------------------------------------
TICK_SECONDS = 4.925490947e-6      # crates/universe/src/view.rs:23 (G M_sun/c^3)
KICK_WAVE_GS = 27.6e3              # 0659/d839: one kick per belt body per doll step
kick_ticks = KICK_WAVE_GS / TICK_SECONDS
SYNODIC_TICKS = 1.1e15             # e828/e87d replica: median-candidate synodic
r = kick_ticks / SYNODIC_TICKS
print(f"\n(C) kick interval = {kick_ticks:.3e} ticks  [e828: 5.7e9; 0659 cadence"
      f" x 1/TICK_SECONDS]")
print(f"    r = passages per touch = {r:.2e}   [e828: 5e-6]")
# independent synodic cross-check: replica cell a-window 1e-4 AU at a=2.5 AU,
# kepler.rs clock 2^32 ticks per time unit (n=1 at a=1): median |da| ~ 2.6e-5 AU
a, half_w = 2.5, 1e-4
for da in (2.6e-5, half_w/2, half_w):
    P_tu = a**1.5                          # period in time units at a
    S_tu = P_tu / (1.5 * da / a)           # synodic, |dP|/P = 1.5 da/a
    S_ticks = S_tu * 2**32
    print(f"    synodic at |da|={da:.1e} AU: {S_ticks:.2e} ticks "
          f"-> r = {kick_ticks/S_ticks:.1e}")
# what 1176's P=4 coupling would require:
need_gs = 4 * SYNODIC_TICKS * TICK_SECONDS
print(f"    P=4 needs one kick per {need_gs:.2e} game-s = "
      f"{need_gs/KICK_WAVE_GS:.1e}x the shipped cadence")
P_ORBIT_GS = 2.5**1.5 * 3.156e7
print(f"    belt orbit ~{P_ORBIT_GS:.2e} game-s -> ~{P_ORBIT_GS/KICK_WAVE_GS:.0f}"
      f" kicks/body/orbit  [1b1f's quote: 0.1-0.25; ~10^4x apart]")

# ---- (D) the like-for-like leak budget ----------------------------------------
LEAK_PT = 7.2e-6                   # 1176: leak per pair per touch at P=4, E large
BUDGET_PT = 1e-6                   # 1a29: real events per candidate per kick
print(f"\n(D) 1176 per candidate per cell kick = {LEAK_PT*2/N_REPLICA:.1e}"
      f" (2/n applied to THEIR side only)  [their quote 7.2e-9, '140x under']")
print(f"    like-for-like per pair per touch: {LEAK_PT:.1e} vs {BUDGET_PT:.0e}"
      f" budget = {LEAK_PT/BUDGET_PT:.0f}x OVER at P=4 — the budget binds at"
      f" 1176's coupling; it does not bind at the game coupling r:")
for E in (64, 256, 1024):
    print(f"      E={E}: passages per blind span = r*E = {r*E:.1e}"
          f" -> per-kick game leak <= {5.2e-6/E:.1e} (e828 bound) << budget")

# ---- (E) the ledger ------------------------------------------------------------
print(f"\n(E) churn row: 08d0-conditional 2.8-5.5 / wholesale-if-9fd1-falls 355"
      f" -> measured-then-corrected: {355/1024:.2f}-{355/256:.1f} cores"
      f" (E*=1024-256)")
old_lo, old_hi = 10.8, 16.6
print(f"    ledger total {old_lo}-{old_hi} -> "
      f"{old_lo-5.5+355/1024:.1f}-{old_hi-2.8+355/256:.1f} cores (conservative"
      f" re-pairing; shift -1.4 to -5.1 cores; the 363-core arm is dead)")

# ---- (F) the reproduced leak surface (e828's epochflux, this box) -------------
print("\n(F) epochflux reproduction (work/out/):")
_here = os.path.dirname(os.path.abspath(__file__))
def _rd(name):
    return open(os.path.join(_here, "out", name)).read()
book, smallh = _rd("book.txt"), _rd("smallh.txt")
s777, s1, sdv0 = _rd("stream-777-q23.txt"), _rd("stream-s1-q23.txt"), _rd("stream-dv0.txt")

# anchors (dossier 5: "anchors w p50 53,946 exact, armed(10^6) 0.7767, dues
# q10/50/90 = 7.5e4/4.7e5/1.8e6")
wa = float(re.search(r"w p50 (\S+)", book).group(1))
ar = float(re.search(r"H=1e6 (\S+)", book).group(1))
q10, q50, q90 = map(float, re.search(
    r"dues q10 (\S+) q50 (\S+) q90 (\S+)", book).groups())
print(f"    book anchors: w p50 {wa:.0f} exact; armed(1e6) {ar:.4f}; "
      f"dues q10/50/90 = {q10:.2e}/{q50:.2e}/{q90:.2e}")
assert wa == 53946.0 and abs(ar - 0.7767) < 5e-4
assert abs(q10 - 7.493e4) < 1 and abs(q50 - 4.663e5) < 1e3 and abs(q90 - 1.776e6) < 1e4

# smallh: dv0 flips zero at every H; deep (H=10^6) flips 0.169-0.174/kick
rows = {m.group(1): [float(x) for x in re.findall(r"flips (\S+)", m.group(2))]
        for m in re.finditer(r"SMALLH (\S+) pairs \d+:(.*)", smallh)}
assert max(rows["dv0"]) == 0.0
deep = [v[-1] for k, v in rows.items() if k != "dv0"]
print(f"    smallh: dv0 flips 0.0 at every H; deep H=10^6 flips "
      f"{min(deep):.3f}-{max(deep):.3f}/kick")
assert abs(min(deep) - 0.1692) < 1e-3 and abs(max(deep) - 0.1742) < 1e-3

# streams: leak rates are exact-count ratios (seeded, deterministic)
def _leaks(text):
    d = {}
    for m in re.finditer(r"E=\s*(\d+)((?:\s+P=\s*\d+:\s*\S+\s*\(\d+ / \d+\))+)", text):
        for p in re.finditer(r"P=\s*(\d+):\s*(\S+)\s*\((\d+) / (\d+)\)", m.group(2)):
            d[(int(m.group(1)), int(p.group(1)))] = (
                float(p.group(2)), int(p.group(3)), int(p.group(4)))
    return d
L7, L1, L0 = _leaks(s777), _leaks(s1), _leaks(sdv0)
assert all(v[1] == 0 for v in L0.values())
v = L7[(1, 1)]
print(f"    777 E=1 P=1: {v[0]:.1e} ({v[1]}/{v[2]}) - zero by construction; "
      f"dv0 zero at every E and P")
v = L7[(2, 1)]
print(f"    777 E=2 P=1: {v[0]:.3e} ({v[1]}/{v[2]})   [e828: 5.2e-6]")
assert v[1] == 8 and abs(v[0] - 5.208e-6) < 1e-9
a, b, c = L7[(2, 1024)], L7[(1024, 1024)], L1[(1024, 1024)]
print(f"    E-shape at P=1024: {a[0]:.2e} (E=2) -> {b[0]:.2e} (E=1024) on 777; "
      f"{c[0]:.2e} on s1 - saturating 1.6e-3 -> 6.8e-2")
assert abs(a[0] - 1.598e-3) < 1e-6 and abs(b[0] - 6.776e-2) < 1e-4
print("    both replicas' raw measurements agree; the conflict was units, not physics")
