#!/usr/bin/env python3
"""Analysis for run 20261012-0138 (second author on 20261012-0036-scout-aac1).

Part A recomputes, from the ORIGINAL run's stored data (data/probe-orig.json, byte-copy
of origin/claude/lab-20261012-0036-scout-aac1:lab/results/.../data/probe.json), every
number the checker flagged as misreported: (a) main walker bins, (b) H2 churned band,
(c) OLR radius from the potential, (d) eval-on-read cost ratio per period, (e) nfail
composition; plus the spatial gate on their own data.

Part B reads the census JSONs (regenerated by probe2.py) and prints the checker's named
experiment: churn census vs window, angle-classifier classes, walker bins, doll-edge
width vs bar strength, and the W1-W6 prediction verdicts.
"""
import json, glob, sys
import numpy as np

# ---------- Part A: corrections from the original stored record ----------
def part_a():
    d = json.load(open('data/probe-orig.json'))
    print('=== A. original record (data/probe-orig.json), recomputed ===')
    for tag in ('main', 'H1_eps10', 'H2_OmP'):
        r = d[tag]
        w = np.array([o['walk'] for o in r['orbits']])
        R = np.array([o['Rg'] for o in r['orbits']])
        print(f"[{r['tag']}] n={r['n']} nfail={r['nfail']} tstat-walk frac={w.mean():.3f}")
        edges = [1.8, 2.3, 2.8, 4.2]
        lo = 0.0
        for hi in edges:
            m = (R >= lo) & (R < hi)
            frac = w[m].sum()/max(w.sum(), 1)
            print(f"   walkers with Rg in [{lo:.1f},{hi:.1f}): {100*frac:.0f}%  "
                  f"(of pop: {100*(m & w).sum()/len(w):.1f}%)")
            lo = hi
        # circular rows = de==0
        print(f"   de==0 rows: {sum(1 for o in r['orbits'] if o['de']==0.0)+0} recorded; "
              f"nfail={r['nfail']} (double-root compile failures, all de=0)")
    # spatial gate on their own data
    for tag in ('main', 'H1_eps10', 'H2_OmP'):
        r = d[tag]
        w = np.array([o['walk'] for o in r['orbits']])
        R = np.array([o['Rg'] for o in r['orbits']])
        flag = R >= 1.8
        tp, fp = int((flag & w).sum()), int((flag & ~w).sum())
        print(f"[{r['tag']}] spatial gate Rg>=1.8: recall={tp/max(w.sum(),1):.2f} "
              f"fpr={fp/max((~w).sum(),1):.2f}")
    ev = d['eval']
    per_period = (ev['step_us_per_orbit']/60.0)/ev['eval_us']
    print(f"eval-on-read vs ONE stepped period: {per_period:.0f}x ; vs the 60-period "
          f"block: {ev['step_us_per_orbit']/ev['eval_us']:.0f}x ; "
          f"compile vs 60-period stepping: {ev['step_us_per_orbit']/ev['compile_us']:.0f}x")
    # OLR/corotation from the potential (m=2: OmP-Om = kap/2 beyond corotation)
    sys.path.insert(0, '.')
    from probe2 import POTS, resonance_radii
    res = resonance_radii('P1', 0.5)
    print(f"P1 OmP=0.5: corotation={res['corotation']}, OLR(m=2)={res['OLR']}, ILR={res['ILR']}")
    res2 = resonance_radii('P1', 0.625)
    print(f"P1 OmP=0.625: corotation={res2['corotation']}, OLR(m=2)={res2['OLR']}, ILR={res2['ILR']}")

# ---------- Part B: the census ----------
def part_b():
    print('\n=== B. census vs window (angle classifier) ===')
    files = sorted(glob.glob('data/census-*.json'))
    cen = {}
    for f in files:
        c = json.load(open(f)); cen[c['tag']] = c
        print(f"\n[{c['tag']}] pot={c['pot']} bar={c['bar']} eps={c['eps']} n={c['n']} "
              f"nfail={c['nfail']} T={c['Tperiods']}p res={ {k:[round(x,3) for x in v] for k,v in c['resonances'].items()} }")
        R = np.array([o['Rg'] for o in c['orbits']])
        de = np.array([o['de'] for o in c['orbits']])
        circ = np.array([o['circular'] for o in c['orbits']])
        for W in [str(w) for w in c['windows']]:
            cl = np.array([o['win'][W]['cls'] for o in c['orbits']])
            nw, nl, nq = int((cl=='walk').sum()), int((cl=='lib').sum()), int((cl=='quiet').sum())
            ts = np.array([o['win'][W]['tstat'] for o in c['orbits']])
            walkR = R[cl=='walk']
            bins = np.histogram(walkR, bins=[0,1.8,2.3,2.8,4.2])[0] if nw else np.zeros(4, int)
            band = (f"[{walkR.min():.2f},{np.percentile(walkR,95):.2f}]"
                    f" width={np.percentile(walkR,95)-walkR.min():.2f}") if nw else "-"
            # former tstat-walkers now classified lib
            reclass = int(((cl=='lib') & (ts>4)).sum())
            print(f"  W={W:>3}p: walk={nw/len(cl):.3f} lib={nl/len(cl):.3f} quiet={nq/len(cl):.3f} "
                  f"| tstat>4: {(ts>4).mean():.3f} | of tstat-walkers, angle says lib: {reclass} "
                  f"| walker bins 0-1.8/1.8-2.3/2.3-2.8/2.8-4.2 = "
                  f"{bins[0]}/{bins[1]}/{bins[2]}/{bins[3]} | band95 {band}")
        if c['Tperiods'] == 600:
            # W6: quiet-orbit E boundedness across windows
            q600 = np.array([o['win']['600']['cls'] for o in c['orbits']]) == 'quiet'
            Ew60 = np.array([o['win']['60']['Ew'] for o in c['orbits']])
            Ew600 = np.array([o['win']['600']['Ew'] for o in c['orbits']])
            dE60 = np.array([o['win']['60']['dE'] for o in c['orbits']])
            dE600 = np.array([o['win']['600']['dE'] for o in c['orbits']])
            ok = (Ew600 <= 3*Ew60)[q600].mean() if q600.any() else float('nan')
            print(f"  W6 (quiet E bounded): frac with Ew(600)<=3*Ew(60): {ok:.3f}; "
                  f"median dE 60p={np.median(dE60[q600]):.4f} 600p={np.median(dE600[q600]):.4f}")
        print(f"  circular rows compiled: {circ.sum()}, nfail={c['nfail']}")

    # width vs eps at fixed window
    print('\n--- doll-edge width vs bar strength (band95 width; p5-p95 of walker Rg) ---')
    for pot, e_list in (('p1', ('e001','e03','e10')), ('p2', ('e001','e03','e10'))):
        for W in ('60', '600'):
            row = []
            for e in e_list:
                for tag, c in cen.items():
                    if tag.startswith(f'{pot}-{e}-') and str(c['Tperiods']) == ('600' if W=='600' else '60') or \
                       (tag.startswith(f'{pot}-{e}-60') and W=='60'):
                        pass
            # simpler: collect below
        break
    def band(tag):
        c = cen[tag]; R = np.array([o['Rg'] for o in c['orbits']])
        W = '60' if c['Tperiods']==60 else '600'
        cl = np.array([o['win'][W]['cls'] for o in c['orbits']])
        wr = R[cl=='walk']
        if len(wr)==0: return (float('nan'),)*3
        return float(wr.min()), float(np.percentile(wr,95)), float(len(wr)/len(cl))
    print(f"{'tag':<14}{'W':>5}{'edge_in':>9}{'edge_out95':>11}{'width':>8}{'frac':>7}")
    for tag in sorted(cen):
        c = cen[tag]
        W = '60' if c['Tperiods']==60 else '600'
        a,b,f = band(tag)
        print(f"{tag:<14}{W:>5}{a:>9.2f}{b:>11.2f}{b-a:>8.2f}{f:>7.3f}")

def part_c():
    """Per-Rg churn profile (the doll-edge curve): walk/lib fractions by radius."""
    print('\n=== C. per-Rg churn profile (doll-edge curve) ===')
    for f in sorted(glob.glob('data/census-*-600.json')):
        c = json.load(open(f))
        print(f"\n[{c['tag']}] (walk/lib fraction per Rg)")
        Rgs = sorted({o['Rg'] for o in c['orbits']})
        for W in ('60', '600'):
            row = []
            for Rg in Rgs:
                cl = np.array([o['win'][W]['cls'] for o in c['orbits'] if o['Rg'] == Rg])
                row.append(f"{(cl=='walk').mean():.0f}/{(cl=='lib').mean():.0f}")
            print(f"  W={W:>3}: " + ' '.join(f"{x:>4s}" for x in row))
        print('  Rg:   ' + ' '.join(f"{r:4.2f}" for r in Rgs))

def part_d():
    """Sustained churn (600-period window) vs effective bar strength eps*A(r_CR)."""
    print('\n=== D. sustained churn vs eps_eff = eps*A(r_corotation) ===')
    _S2 = 1.2*1.2
    A = {'P1': (lambda r: r*r/(r*r+1.0)), 'P2': (lambda r: (r*r/_S2)*np.exp(1.0-(r*r/_S2)))}
    rows = []
    for f in sorted(glob.glob('data/census-*-600.json')):
        c = json.load(open(f))
        rc = c['resonances']['corotation'][0]
        ee = c['eps']*A[c['pot']](rc)
        cl = np.array([o['win']['600']['cls'] for o in c['orbits']])
        R = np.array([o['Rg'] for o in c['orbits']])
        wr = R[cl=='walk']
        band = f"[{wr.min():.2f},{np.percentile(wr,95):.2f}]" if len(wr) else "-"
        rows.append((ee, c['tag'], (cl=='walk').mean(), (cl=='lib').mean(), band))
    for ee, tag, w, l, band in sorted(rows):
        print(f"  eps_eff={ee:.5f}  {tag:<14} walk600={w:.3f} lib600={l:.3f} band95={band}")

if __name__ == '__main__':
    part_a()
    part_b()
    part_c()
    part_d()
